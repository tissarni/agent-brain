#!/usr/bin/env node
// Deterministic single-file markdown -> standalone HTML compiler.
// Reuses doc-build's renderer + design (same CSS, same markdown dialect, same
// wikilink handling) so every HTML artifact in the vault looks the same.
//
// Usage: node build.js <file.md> [output-path]
//   - output defaults to <file>.html next to the source .md
//   - a frontmatter `title` (or the first `# heading`) becomes the page title
//
// No LLM pass, no summarizing — same .md in, same .html out, every run.
'use strict';

const fs = require('fs');
const path = require('path');
const docBuild = require('../doc-build/build.js');

const { readFile, parseFrontmatter, renderMarkdown, renderInline, escapeHtml, CSS, LOGO_HTML } = docBuild;

function deriveTitle(meta, body, filePath) {
  if (meta.title) return meta.title;
  const h = /^#\s+(.+)$/m.exec(body);
  if (h) return h[1].trim();
  return path.basename(filePath, '.md');
}

function stripFences(body) {
  return body.replace(/^(```+|~~~+)[\s\S]*?^\1[ \t]*$/gm, '');
}

function deriveSummary(body) {
  // First plain paragraph after the title — a README's opening sentence is
  // exactly what a sidebar summary should say. Inline markup is dropped.
  const lines = stripFences(body).split('\n');
  let start = -1;
  for (let i = 0; i < lines.length; i++) {
    const l = lines[i].trim();
    if (!l || /^#/.test(l) || /^[-*>|]/.test(l)) continue;
    start = i;
    break;
  }
  if (start < 0) return '';
  const para = [];
  for (let i = start; i < lines.length && lines[i].trim(); i++) para.push(lines[i].trim());
  return para.join(' ').replace(/[`*_]/g, '').replace(/\[([^\]]+)\]\([^)]*\)/g, '$1');
}

function buildToc(body) {
  // Collect the document's major sections for the sidebar TOC: `##` headings
  // only (the `#` is the page title, `###`+ is subsection detail — listing
  // those makes the TOC unreadable on command-heavy guides).
  // CRITICAL: skip fenced code blocks — a `# comment` line inside a shell
  // fence matches the heading regex and used to flood the TOC.
  const items = [];
  let inFence = false;
  for (const line of body.split('\n')) {
    if (/^(```+|~~~+)/.test(line.trim())) {
      inFence = !inFence;
      continue;
    }
    if (inFence) continue;
    const m = /^##\s+(.+)$/.exec(line);
    if (!m) continue;
    const text = m[1].trim();
    const slug = docBuild.slugify(text);
    if (items.some((it) => it.slug === slug)) continue; // first occurrence wins for anchors
    items.push({ text, slug });
  }
  return items;
}

function main() {
  const input = process.argv[2];
  if (!input) {
    console.error('usage: node build.js <file.md> [output-path]');
    process.exit(1);
  }
  const inPath = path.resolve(input);
  if (!fs.existsSync(inPath)) {
    console.error(`no such file: ${inPath}`);
    process.exit(1);
  }
  if (!/\.md$/i.test(inPath)) {
    console.error(`not a markdown file: ${inPath}`);
    process.exit(1);
  }
  const outPath = process.argv[3] ? path.resolve(process.argv[3]) : inPath.replace(/\.md$/i, '.html');

  const raw = readFile(inPath);
  const { meta, body } = parseFrontmatter(raw);
  const title = deriveTitle(meta, body, inPath);
  const summary = meta.summary || deriveSummary(body);
  const kicker = meta.kind || (/^readme$/i.test(path.basename(inPath, '.md')) ? 'readme' : '');

  // Headings keep their level: `#` is the page title (styled below as the
  // content h1), `##` are the h2 sections doc-build pages use, so the TOC and
  // the section styling match. A body with no `#` gets one from the title.
  const hasH1 = /^#\s+\S/m.test(stripFences(body));
  const bodyHtml = (hasH1 ? '' : `<h1 id="${docBuild.slugify(title)}">${escapeHtml(title)}</h1>\n`) +
    renderMarkdown(body, { headingOffset: 0, baseDir: path.dirname(inPath) });
  const tocItems = buildToc(body);

  const tocHtml = tocItems
    .map((it) => `<li><a href="#${it.slug}">${escapeHtml(it.text)}</a></li>`)
    .join('\n');

  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(title)}</title>
<style>${CSS}
.content > h1 { font-size: 2.2rem; margin: 0 0 1.2rem; padding-bottom: 0.6rem; border-bottom: 3px solid var(--brand); }</style>
</head>
<body>
<!-- GENERATED by md-html from ${escapeHtml(path.basename(inPath))} — do not hand-edit; rerun to refresh -->
<aside class="sidebar">
${LOGO_HTML}
${kicker ? `<div class="kicker">${escapeHtml(kicker)}</div>` : ''}
<h1>${escapeHtml(title)}</h1>
${summary ? `<p class="summary">${escapeHtml(summary)}</p>` : ''}
<nav class="toc"><strong>Contents</strong><ul>${tocHtml}</ul></nav>
</aside>
<div class="content-wrap">
<main class="content">
${bodyHtml}
<footer>
Generated ${escapeHtml(new Date().toISOString().slice(0, 16).replace('T', ' ') + ' UTC')} from
<code>${escapeHtml(path.basename(inPath))}</code>.
</footer>
</main>
</div>
</body>
</html>
`;

  fs.writeFileSync(outPath, html, 'utf8');
  console.log(`built ${outPath}`);
  console.log(`source: ${path.basename(inPath)}`);
}

if (require.main === module) main();
